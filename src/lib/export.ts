/**
 * Exports: compiled JSON, a Godot 4.3+ project (QuestManager autoload + QuestLog control + Easy Dialogue
 * runner wired through the bridge) and a PixiJS v8 bundle (manager + quest-log view + playable demo).
 */

export const EXPORT_PRESETS = ["json", "godot", "pixi", "all"] as const;
export type ExportPreset = (typeof EXPORT_PRESETS)[number];

export interface ExportOptions {
  id: string;
  preset?: ExportPreset;
  /** Output folder (default `exports/<id>-<preset>`). Relative paths resolve inside the workspace. */
  out?: string;
  style?: BoxStyle;
  /** Picks the demo scene plays the first linked dialogue with (default 0,0). */
  picks?: number[];
  background?: string | null;
  /** CLI callers may write anywhere they named; API/MCP stay inside the workspace. */
  trustedPaths?: boolean;
}

export interface ExportResult {
  preset: ExportPreset;
  dirs: string[];
  files: string[];
  warnings: string[];
}

class Writer {
  files: string[] = [];
  constructor(public root: string) {}
  async text(rel: string, body: string) {
    const f = path.join(this.root, rel);
    await mkdir(path.dirname(f), { recursive: true });
    await writeFile(f, body);
    this.files.push(f);
  }
  async bin(rel: string, body: Buffer) {
    const f = path.join(this.root, rel);
    await mkdir(path.dirname(f), { recursive: true });
    await writeFile(f, body);
    this.files.push(f);
  }
  async copy(src: string, rel: string) {
    const f = path.join(this.root, rel);
    await mkdir(path.dirname(f), { recursive: true });
    await copyFile(src, f);
    this.files.push(f);
  }
}

interface Ctx {
  root: string;
  doc: QuestDoc;
  style: BoxStyle;
  picks: number[];
  background: string | null;
  dialogues: Array<{ id: string; doc: unknown }>;
  warnings: string[];
}

/** UI art shared by Godot and Pixi: frames, item icons, state icons, giver portraits, fonts, background. */
async function writeUi(w: Writer, ctx: Ctx, uiDir: string) {
  await w.bin(`${uiDir}/box_${ctx.style}.png`, pixelsPng(boxFrame(ctx.style)));
  await w.bin(`${uiDir}/plate_${ctx.style}.png`, pixelsPng(plateFrame(ctx.style)));
  await w.bin(`${uiDir}/well_${ctx.style}.png`, pixelsPng(wellFrame(ctx.style)));
  for (const n of ICON_NAMES) await w.bin(`${uiDir}/icons/${n}.png`, pixelsPng(itemIcon(n)));
  for (const n of STATE_ICONS) await w.bin(`${uiDir}/state/${n}.png`, pixelsPng(stateIcon(n)));
  const sets = new Set<string>();
  for (const d of ctx.doc.dialogues) for (const c of Object.values(d.cast)) if (c.portrait) sets.add(c.portrait);
  for (const s of sets) {
    const f = portraitFile(ctx.root, s);
    if (f) await w.copy(f, `portraits/${s}/neutral.png`);
  }
  await w.copy(path.join(FONT_DIR, "Kanit-Regular.ttf"), "fonts/Kanit-Regular.ttf");
  await w.copy(path.join(FONT_DIR, "Kanit-Medium.ttf"), "fonts/Kanit-Medium.ttf");
  await w.copy(path.join(FONT_DIR, "OFL.txt"), "fonts/OFL.txt");
  if (ctx.background) await w.copy(ctx.background, "background.png");
}

