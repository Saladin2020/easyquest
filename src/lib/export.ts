async function exportPixi(w: Writer, ctx: Ctx) {
  const id = ctx.doc.id;
  const d = ctx.dialogues[0] ?? null;
  await w.text(`${id}.quests.json`, `${JSON.stringify(ctx.doc)}\n`);
  for (const x of ctx.dialogues) await w.text(`${x.id}.dialogue.json`, `${JSON.stringify(x.doc)}\n`);
  for (const f of ["easyquest-manager.js", "easyquest-log.js", "easyquest-pixi.js", "easydialogue-runner.js"]) await w.copy(path.join(RUNTIME_DIR, "pixi", f), f);
  await writeUi(w, ctx, "ui");
  await w.text("index.html", PIXI_HTML(ctx.doc.title, id, d?.id ?? null, ctx.picks));
}

export async function exportQuests(root: string, opts: ExportOptions): Promise<ExportResult> {
  const id = assertSafeId(opts.id);
  const preset = opts.preset ?? "all";
  const doc = await compileById(root, id);
  const warnings: string[] = [];
  const dialogues: Ctx["dialogues"] = [];
  for (const link of doc.dialogues) {
    if (!link.found) continue;
    try {
      const d = await loadCompiledDialogue(root, link.id);
      if (d.warning) warnings.push(d.warning);
      dialogues.push({ id: link.id, doc: d.doc });
    } catch (e) {
      warnings.push(e instanceof Error ? e.message : String(e));
    }
  }
  if (!dialogueFiles(root, doc.dialogues[0]?.id ?? "").json && doc.dialogues.length && !dialogues.length) warnings.push("The demo scene needs a compiled dialogue (dialogues/<id>.dialogue.json)");
  const bg = opts.background === null ? null : (backgroundFile(root, opts.background ?? "thai_village_topdown") ?? null);
  const ctx: Ctx = { root, doc, style: opts.style ?? "teak", picks: opts.picks ?? [0, 0], background: bg && existsSync(bg) ? bg : null, dialogues, warnings };
  const presets: Exclude<ExportPreset, "all">[] = preset === "all" ? ["json", "godot", "pixi"] : [preset];
  const outFor = (p: string) => {
    const base = opts.out ? (presets.length > 1 ? path.join(opts.out, p) : opts.out) : path.join(path.relative(root, dirs(root).exports) || "exports", `${id}-${p}`);
    return opts.trustedPaths ? path.resolve(root, base) : resolveInside(root, base);
  };
  const res: ExportResult = { preset, dirs: [], files: [], warnings };
  for (const p of presets) {
    const w = new Writer(outFor(p));
    if (p === "json") await w.text(`${id}.quests.json`, `${JSON.stringify(doc, null, 2)}\n`);
    else if (p === "godot") await exportGodot(w, ctx);
    else await exportPixi(w, ctx);
    res.dirs.push(w.root);
    res.files.push(...w.files);
  }
  return res;
}
