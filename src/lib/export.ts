import { QuestManager, bridgeDialogue } from "./easyquest-manager.js";
import { DialogueRunner } from "./easydialogue-runner.js";
import { QuestLogView, DialogueStrip } from "./easyquest-pixi.js";

const PIXI = await loadPixi();
await Promise.all([document.fonts.load('24px "Kanit"'), document.fonts.load('24px "Kanit Medium"')]);
const S = 3;
const app = new PIXI.Application();
await app.init({ width: 480 * S, height: 300 * S, background: "#0d0906", antialias: false });
document.getElementById("game").append(app.canvas);

