const MAIN_GD = (quests: string, dialogue: string | null, picks: number[]) => `extends Control
## Easy Quest demo: plays the linked Easy Dialogue script through the bridge while the quest log updates.
## Space / Enter: next line · 1-3: pick a choice · ↑/↓: select a quest · R: restart.

const Runner = preload("res://addons/easydialogue/dialogue_runner.gd")
@export var quests_path := "res://quests/${quests}.quests.json"
@export var dialogue_path := ${dialogue ? `"res://dialogue/${dialogue}.dialogue.json"` : `""`}
@export var dialogue_id := "${dialogue ?? ""}"
## Auto-play these picks (positions in the visible options) every \`auto_delay\` seconds; empty = manual.
@export var auto_picks: Array = ${JSON.stringify(picks)}
@export var auto_delay := 0.15

var qm: Node
var runner
var pending: Dictionary = {}
var pick_i := 0
var timer := 0.0
var finished := false
var screenshot := ""
var after := 0
@onready var line_label: Label = $Bar/Line


func _ready() -> void:
	# The QuestManager autoload (project.godot); a local one if this scene is used without it.
	qm = get_node_or_null("/root/QuestManager")
	if qm == null:
		qm = load("res://addons/easyquest/quest_manager.gd").new()
		qm.name = "QuestManager"
		add_child(qm)
	$QuestLog.bind(qm)
	for a in OS.get_cmdline_user_args():
		if a.begins_with("screenshot="):
			screenshot = a.substr(11)
			auto_delay = 0.01
	qm.load_file(quests_path)
	_start_dialogue()


func _start_dialogue() -> void:
	if dialogue_path == "" or not FileAccess.file_exists(dialogue_path):
		line_label.text = "(no linked dialogue)"
		return
	runner = Runner.new()
	runner.load_file(dialogue_path)
	qm.connect_dialogue(runner, dialogue_id)
	runner.start()
	finished = false
	_advance()


func _advance() -> void:
	if runner == null or finished:
		return
	if not pending.is_empty():
		return
	var ev: Dictionary = runner.next()
	match ev["type"]:
		"line":
			var who = ev.get("name")
			line_label.text = ("%s: %s" % [who, ev["text"]]) if who != null and str(who) != "" else str(ev["text"])
		"choices":
			pending = ev
			var t := []
			var n := 1
			for o in ev["options"]:
				if not bool(o.get("disabled", false)):
					t.append("%d) %s" % [n, o["text"]])
					n += 1
			line_label.text = "   ".join(t)
		"end":
			finished = true
			qm.dialogue_ended(runner, dialogue_id)
			line_label.text = "— จบบทสนทนา (R เริ่มใหม่) —"


func _choose(k: int) -> void:
	var live: Array = []
	for o in pending["options"]:
		if not bool(o.get("disabled", false)):
			live.append(o)
	var o: Dictionary = live[mini(k, live.size() - 1)]
	pending = {}
	runner.choose(int(o["index"]))
	_advance()


func _process(delta: float) -> void:
	if screenshot != "" and finished:
		after += 1
		if after == 10:
			get_viewport().get_texture().get_image().save_png(screenshot)
			print("saved ", screenshot)
			get_tree().quit()
		return
	if auto_picks.is_empty() and auto_delay <= 0.0:
		return
	if finished or runner == null:
		return
	timer += delta
	if timer < auto_delay:
		return
	timer = 0.0
	if not pending.is_empty():
		_choose(int(auto_picks[pick_i]) if pick_i < auto_picks.size() else 0)
		pick_i += 1
	else:
		_advance()


func _unhandled_input(event: InputEvent) -> void:
	if not (event is InputEventKey and event.pressed):
		return
	if event.keycode in [KEY_SPACE, KEY_ENTER]:
		auto_delay = 0.0
		_advance()
	elif event.keycode >= KEY_1 and event.keycode <= KEY_9 and not pending.is_empty():
		auto_delay = 0.0
		_choose(event.keycode - KEY_1)
	elif event.keycode == KEY_R:
		pick_i = 0
		pending = {}
		qm.load_file(quests_path)
		_start_dialogue()
`;

