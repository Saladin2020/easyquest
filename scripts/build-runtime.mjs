/**
 * Bundle the shared quest-log drawing (src/shared/questlog.ts + frames + icons) into
 * runtime/pixi/easyquest-log.js for the PixiJS export. The manager and the vendored Easy Dialogue runner
 * stay separate files next to it. Usage: node scripts/build-runtime.mjs [--check]
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const out = path.join(root, "runtime", "pixi", "easyquest-log.js");
const siblings = {
  name: "runtime-siblings",
  setup(b) {
    b.onResolve({ filter: /runtime\/pixi\/(easyquest-manager|easydialogue-runner)\.js$/ }, (a) => ({ path: `./${path.basename(a.path)}`, external: true }));
  },
};
const res = await build({
  entryPoints: [path.join(root, "src", "shared", "logRuntime.ts")],
  bundle: true,
  format: "esm",
  platform: "browser",
  target: "es2020",
  write: false,
  legalComments: "none",
  plugins: [siblings],
  banner: { js: "// Easy Quest log drawing for browsers / PixiJS — generated by scripts/build-runtime.mjs from src/shared/questlog.ts. Do not edit.\n// MIT (code) · CC0 (pixel frames and icons). https://github.com/Saladin2020/easyquest" },
});
const code = res.outputFiles[0].text;
if (process.argv.includes("--check")) {
  const cur = readFileSync(out, "utf8");
  if (cur !== code) {
    console.error("runtime/pixi/easyquest-log.js is out of date — run node scripts/build-runtime.mjs");
    process.exit(1);
  }
  console.log("easyquest-log.js up to date");
} else {
  writeFileSync(out, code);
  console.log(`wrote ${path.relative(root, out)} (${code.length} bytes)`);
}
